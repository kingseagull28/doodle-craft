  // ---------- block textures ----------
  function blockTexture(spec, seedStr) {
    var r = rng(hash(seedStr || 'x'));
    var a = spec.a || '#888888', b = spec.b || shade(a, -0.3), x = spec.x || '#ffffff';
    var px = [];
    for (var yy = 0; yy < 16; yy++) px.push(new Array(16).fill(null));
    function set(xx, y, c) { if (xx >= 0 && xx < 16 && y >= 0 && y < 16) px[y][xx] = c; }
    function noise(base, amt, xx, y) {
      var v = r();
      if (v < 0.25) return shade(base, -amt);
      if (v < 0.45) return shade(base, amt);
      if (v < 0.52) return shade(base, -amt * 2);
      return base;
    }
    var s = spec.s || 'noise';
    var X, Y;
    switch (s) {
      case 'planks':
        for (Y = 0; Y < 16; Y++) for (X = 0; X < 16; X++) {
          var row = Math.floor(Y / 4), seam = (row * 5 + 3) % 16;
          var c = noise(a, 0.06);
          if (Y % 4 === 3) c = shade(a, -0.32);
          else if (X === seam) c = shade(a, -0.25);
          else if (Y % 4 === 0) c = shade(a, 0.08);
          set(X, Y, c);
        }
        break;
      case 'log':
        var cols = [];
        for (X = 0; X < 16; X++) { var v = r(); cols.push(v < 0.33 ? shade(a, -0.18) : v < 0.6 ? shade(a, 0.1) : a); }
        for (Y = 0; Y < 16; Y++) for (X = 0; X < 16; X++) {
          var cc = cols[X];
          if (spec.b && r() < (spec.spots ? 0.1 : 0.04)) cc = spec.spots ? spec.spotColor || '#333333' : shade(a, -0.3);
          set(X, Y, cc);
        }
        break;
      case 'cobble':
        var pts = [];
        for (var i = 0; i < 11; i++) pts.push([r() * 16, r() * 16, r() < 0.5 ? shade(a, 0.1) : r() < 0.5 ? a : shade(a, -0.12)]);
        for (Y = 0; Y < 16; Y++) for (X = 0; X < 16; X++) {
          var d1 = 99, d2 = 99, best = null;
          for (var k = 0; k < pts.length; k++) {
            for (var ox = -16; ox <= 16; ox += 16) for (var oy = -16; oy <= 16; oy += 16) {
              var dx = pts[k][0] + ox - X, dy = pts[k][1] + oy - Y, d = Math.sqrt(dx * dx + dy * dy);
              if (d < d1) { d2 = d1; d1 = d; best = pts[k][2]; } else if (d < d2) d2 = d;
            }
          }
          set(X, Y, d2 - d1 < 0.9 ? shade(a, -0.35) : best);
        }
        break;
      case 'bricks':
        for (Y = 0; Y < 16; Y++) for (X = 0; X < 16; X++) {
          var rw = Math.floor(Y / 4), off = rw % 2 ? 4 : 0;
          var mortar = Y % 4 === 3 || (X + off) % 8 === 7;
          set(X, Y, mortar ? (spec.m || shade(a, 0.45)) : noise(a, 0.06));
        }
        break;
      case 'stonebricks':
        for (Y = 0; Y < 16; Y++) for (X = 0; X < 16; X++) {
          var rw2 = Math.floor(Y / 8), off2 = rw2 % 2 ? 8 : 0;
          var line = Y % 8 === 7 || (X + off2) % 16 === 15;
          var top = Y % 8 === 0 || (X + off2) % 16 === 0;
          set(X, Y, line ? shade(a, -0.35) : top ? shade(a, 0.12) : noise(a, 0.05));
        }
        if (spec.moss) for (var m = 0; m < 40; m++) set(Math.floor(r() * 16), Math.floor(r() * 16), r() < 0.5 ? '#5a7d32' : '#47652a');
        if (spec.crack) { var cx = 4; for (Y = 1; Y < 15; Y++) { cx += Math.round(r() * 2 - 1); set(cx, Y, shade(a, -0.5)); } }
        break;
      case 'chiseled':
        for (Y = 0; Y < 16; Y++) for (X = 0; X < 16; X++) {
          var edge = X === 0 || Y === 0 || X === 15 || Y === 15;
          var ring = (X === 3 || X === 12) && Y >= 3 && Y <= 12 || (Y === 3 || Y === 12) && X >= 3 && X <= 12;
          set(X, Y, edge ? shade(a, -0.3) : ring ? shade(a, -0.22) : noise(a, 0.04));
        }
        set(7, 7, shade(a, -0.3)); set(8, 8, shade(a, -0.3)); set(7, 8, shade(a, 0.15)); set(8, 7, shade(a, 0.15));
        break;
      case 'smooth':
        for (Y = 0; Y < 16; Y++) for (X = 0; X < 16; X++) {
          var e = X === 0 || Y === 0 ? shade(a, 0.12) : X === 15 || Y === 15 ? shade(a, -0.18) : (r() < 0.12 ? shade(a, -0.04) : a);
          set(X, Y, e);
        }
        break;
      case 'pillar':
        for (Y = 0; Y < 16; Y++) for (X = 0; X < 16; X++) {
          var pl = X % 5 === 0 ? shade(a, -0.15) : X % 5 === 1 ? shade(a, 0.1) : a;
          if (Y === 0 || Y === 15) pl = shade(a, -0.2);
          set(X, Y, pl);
        }
        break;
      case 'metal':
        for (Y = 0; Y < 16; Y++) for (X = 0; X < 16; X++) {
          var c2 = a;
          if (X === 0 || Y === 0) c2 = shade(a, 0.35);
          else if (X === 15 || Y === 15) c2 = shade(a, -0.35);
          else if ((X === 2 || Y === 2) && X < 14 && Y < 14) c2 = shade(a, -0.15);
          else if ((X === 13 || Y === 13) && X > 1 && Y > 1) c2 = shade(a, 0.2);
          else if (r() < 0.1) c2 = shade(a, 0.08);
          set(X, Y, c2);
        }
        break;
      case 'glass':
        for (Y = 0; Y < 16; Y++) for (X = 0; X < 16; X++) {
          var edg = X === 0 || Y === 0 || X === 15 || Y === 15;
          if (edg) set(X, Y, shade(a, -0.1));
          else if ((X + Y === 6) || (X + Y === 7) || (X + Y === 18)) set(X, Y, '#ffffffcc');
          else set(X, Y, spec.tint ? spec.tint : a + '55');
        }
        break;
      case 'wool':
        for (Y = 0; Y < 16; Y++) for (X = 0; X < 16; X++) {
          var w = noise(a, 0.05);
          if ((X + Y * 3) % 7 === 0) w = shade(a, -0.08);
          set(X, Y, w);
        }
        break;
      case 'speckle':
        for (Y = 0; Y < 16; Y++) for (X = 0; X < 16; X++) set(X, Y, r() < (spec.p || 0.12) ? (r() < 0.5 ? b : (spec.x || shade(a, 0.25))) : noise(a, 0.05));
        break;
      case 'lamp':
        for (Y = 0; Y < 16; Y++) for (X = 0; X < 16; X++) {
          var lv = r();
          set(X, Y, lv < 0.4 ? a : lv < 0.7 ? shade(a, 0.3) : b);
        }
        for (X = 0; X < 16; X++) { set(X, 0, b); set(X, 15, b); set(0, X, b); set(15, X, b); }
        break;
      case 'stripes':
        for (Y = 0; Y < 16; Y++) for (X = 0; X < 16; X++) {
          var st = Math.floor(X / 3) % 2 ? b : a;
          if (Y === 0 || Y === 15) st = shade(st, -0.15);
          set(X, Y, r() < 0.08 ? shade(st, 0.12) : st);
        }
        if (spec.stem) { set(7, 0, '#5a7d32'); set(8, 0, '#47652a'); set(7, 1, '#5a7d32'); }
        break;
      case 'hay':
        for (Y = 0; Y < 16; Y++) for (X = 0; X < 16; X++) {
          var band = (Y >= 4 && Y <= 5) || (Y >= 10 && Y <= 11);
          set(X, Y, band ? b : (X % 2 ? a : shade(a, 0.15)));
        }
        break;
      case 'translucent':
        for (Y = 0; Y < 16; Y++) for (X = 0; X < 16; X++) {
          var inner = X >= 3 && X <= 12 && Y >= 3 && Y <= 12;
          var ed = X === 0 || Y === 0 || X === 15 || Y === 15;
          set(X, Y, ed ? shade(a, -0.25) : inner ? b : a + 'cc');
        }
        break;
      case 'shelf':
        var bookCols = ['#a33a2a', '#2e5a8a', '#3f7a35', '#c99a2e', '#6a3d8a', '#c0c0c0', '#8a4a25'];
        for (Y = 0; Y < 16; Y++) for (X = 0; X < 16; X++) {
          if (Y < 2 || Y > 13 || Y === 7 || Y === 8) { set(X, Y, Y === 1 || Y === 8 || Y === 14 ? shade(a, -0.3) : a); continue; }
          set(X, Y, X % 2 ? shade(bookCols[(X + (Y > 8 ? 3 : 0)) % bookCols.length], -0.1) : bookCols[(X + (Y > 8 ? 3 : 0)) % bookCols.length]);
          if (Y === 2 || Y === 9) set(X, Y, shade(px[Y][X], -0.35));
        }
        break;
      default: // noise
        for (Y = 0; Y < 16; Y++) for (X = 0; X < 16; X++) set(X, Y, noise(a, spec.amt || 0.07));
    }
    if (spec.face) drawFace(px, spec.face, spec, r);
    return px;
  }

