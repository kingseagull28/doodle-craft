  function render(spec, id) {
    var out = [];
    var i, x, y;
    if (spec.t === 'block' || spec.t === 'mask') {
      var base = spec.t === 'mask' ? spec.base : spec;
      var tex = blockTexture(base, id + (spec.t === 'mask' ? ':' + spec.m : ''));
      var mask = M[spec.t === 'mask' ? spec.m : 'full'];
      for (y = 0; y < 16; y++) for (x = 0; x < 16; x++) out.push(mask[y][x] === '#' ? tex[y][x] : null);
      // soft bevel + outline for shaped (non-full) pieces
      if (spec.t === 'mask') addOutline(out);
      return out;
    }
    var tpl = T[spec.t];
    if (!tpl) throw new Error('Unknown icon template: ' + spec.t + ' for ' + id);
    var pal = palette(spec);
    for (y = 0; y < 16; y++) for (x = 0; x < 16; x++) {
      var ch = tpl[y][x];
      out.push(ch === '.' ? null : (pal[ch] || '#ff00ff'));
    }
    if (spec.outline !== false) addOutline(out);
    return out;
  }

  function addOutline(out) {
    var copy = out.slice();
    for (var y = 0; y < 16; y++) for (var x = 0; x < 16; x++) {
      var idx = y * 16 + x;
      if (copy[idx]) continue;
      var n = null;
      var nb = [[1, 0], [-1, 0], [0, 1], [0, -1]];
      for (var k = 0; k < 4; k++) {
        var nx = x + nb[k][0], ny = y + nb[k][1];
        if (nx < 0 || ny < 0 || nx > 15 || ny > 15) continue;
        var c = copy[ny * 16 + nx];
        if (c) { n = c; break; }
      }
      if (n) out[idx] = shade(n.slice(0, 7), -0.62);
    }
  }

  function validateTemplates() {
    var errs = [];
    Object.keys(T).forEach(function (k) {
      if (T[k].length !== 16) errs.push(k + ': has ' + T[k].length + ' rows');
      T[k].forEach(function (row, i) { if (row.length !== 16) errs.push(k + ' row ' + i + ': length ' + row.length); });
    });
    Object.keys(M).forEach(function (k) { if (M[k].length !== 16) errs.push('mask ' + k); });
    return errs;
  }

  // ---------- browser: draw to canvas, cached data URLs ----------
  var cache = {};
  function toDataURL(spec, id) {
    if (cache[id]) return cache[id];
    if (typeof document === 'undefined') return '';
    var px = render(spec, id);
    var cv = document.createElement('canvas');
    cv.width = 16; cv.height = 16;
    var ctx = cv.getContext('2d');
    var img = ctx.createImageData(16, 16);
    for (var i = 0; i < 256; i++) {
      var c = px[i];
      if (!c) continue;
      var rgb = hexToRgb(c);
      img.data[i * 4] = rgb[0]; img.data[i * 4 + 1] = rgb[1]; img.data[i * 4 + 2] = rgb[2]; img.data[i * 4 + 3] = rgb[3];
    }
    ctx.putImageData(img, 0, 0);
    cache[id] = cv.toDataURL('image/png');
    return cache[id];
  }

